"""scripts/gen_transient_web_data.py — M3 mode basis for the Web TS core.

PUT-IN     : reference/plate_transient.build_basis() (512-pt tables, masses).
EMERGED    : nothing — pure data transfer.
CLAIM-TIER : measured (numeric record).
FLOORS     : modes truncated at 1300 Hz (see plate_transient floors).
Writes webapp/src/data/plate_modes_transient.json.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from reference import plate_transient as pt

basis = pt.build_basis()
try:
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
except Exception:
    commit = "unknown"
out = dict(schema="physicymatics.plate_modes_transient.v1",
           _provenance="GENERATED by scripts/gen_transient_web_data.py; do not hand-edit.",
           source_commit=commit, a_m=float(basis["a"]), ngrid=int(basis["ngrid"]),
           zeta=pt.ZETA, normalization="max|R|=1",
           modes=[dict(m=int(md["m"]), root_idx=int(md["root_idx"]), f_hz=float(md["f_hz"]),
                       M_kg=float(md["M_kg"]),
                       R=[float(v) for v in md["R"]], dR_drho=[float(v) for v in md["dR"]])
                  for md in basis["modes"]])
path = os.path.join(ROOT, "webapp", "src", "data", "plate_modes_transient.json")
json.dump(out, open(path, "w"), separators=(",", ":"))
print(f"wrote {path}: {len(out['modes'])} modes, {len(basis['dofs'])} dofs")
