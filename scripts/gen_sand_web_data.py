"""scripts/gen_sand_web_data.py — Web sand data from the Python reference.

PUT-IN     : reference/sand_bounce.make_mode(0,0) (4096-pt signed table),
             tests/fixtures/sand/m1_short.npz (oracle short run).
EMERGED    : nothing — pure data transfer (no resampling, no interpolation).
CLAIM-TIER : measured (numeric record).
FLOORS     : table is mode (0,1) only (M1/M2 scope); pack's 129-pt preview
             table is NOT used for contact physics.

Writes webapp/src/data/sand_mode01.json + truth/sand_m1_short.json.
"""
import json, os, subprocess, sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from reference import sand_bounce as sb

DATA = os.path.join(ROOT, "webapp", "src", "data")


def main():
    mode = sb.make_mode(0, 0)
    try:
        commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        commit = "unknown"
    out = dict(schema="physicymatics.sand_mode.v1",
               _provenance="GENERATED by scripts/gen_sand_web_data.py from reference/sand_bounce.make_mode(0,0); do not hand-edit.",
               source_commit=commit, m=int(mode["m"]), root_idx=0,
               f_hz=float(mode["f_hz"]), a_m=float(mode["a"]),
               ngrid=int(mode["ngrid"]), normalization="max|R|=1",
               r_nodes_over_a=[float(v) for v in mode["r_nodes"]],
               R=[float(v) for v in mode["R"]],
               dR_drho=[float(v) for v in mode["dR"]])
    json.dump(out, open(os.path.join(DATA, "sand_mode01.json"), "w"),
              separators=(",", ":"))
    d = np.load(os.path.join(ROOT, "tests", "fixtures", "sand", "m1_short.npz"))
    truth = dict(_provenance="tests/fixtures/sand/m1_short.npz (oracle c002b, 50 particles, 0.3 s)",
                 init_x=[float(v) for v in d["init_x"]], init_y=[float(v) for v in d["init_y"]],
                 x=[float(v) for v in d["x"]], y=[float(v) for v in d["y"]],
                 sitting=[bool(v) for v in d["sitting"]],
                 n_bounce=int(d["n_bounce"]), t_max_s=0.3, Gamma=80)
    json.dump(truth, open(os.path.join(DATA, "truth", "sand_m1_short.json"), "w"),
              separators=(",", ":"))
    print(f"wrote sand_mode01.json (ngrid={out['ngrid']}, f={out['f_hz']:.4f}) + truth/sand_m1_short.json")


if __name__ == "__main__":
    main()
